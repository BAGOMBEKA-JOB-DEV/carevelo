import { postAndKeepSession, type SessionCall } from './http'
import type { Operator } from '../model/roles'
import { problemFor, type SignInProblem } from '../model/signIn'

/**
 * The two calls that sign a platform operator in, and the one that signs them out.
 *
 * ============================================================
 * THE PASSWORD CALL RETURNS NO SESSION, AND THAT IS THE CONTROL
 * ============================================================
 *
 * `POST /v1/platform/auth/sign-in` proves a password and calls no guard. Until a code
 * verifies there is no authenticated session anywhere in the system — not a narrowed one,
 * not a restricted one, none. docs/40-api/authentication-and-sessions.md states it as
 * testable rule 5: "Platform operators cannot authenticate without a second factor."
 *
 * What the call DOES leave behind is a pending challenge in the session, which is why both
 * of these go through `postAndKeepSession()` rather than the ordinary `writeClient()`: the
 * cookie the API sets on the first response has to be re-issued on this app's own response,
 * or the second request arrives with nothing to verify against.
 *
 * ============================================================
 * ON TYPES
 * ============================================================
 *
 * `Operator` is reused from model/roles — `components['schemas']['MeResource']` out of the
 * generated client — because the challenge endpoint returns exactly the resource
 * `GET /v1/platform/me` does. One definition, so the two cannot drift.
 *
 * The password step's body is the one shape in this file that is written out by hand, and
 * it is not there by choice: `docs/40-api/openapi.yaml` is generated by
 * `php artisan api:contract`, which reads column types out of a live database, and that
 * database could not be started in the change that added these endpoints. So the contract
 * does not yet describe `/v1/platform/auth/*`, and the generated client cannot either.
 *
 * THIS IS A DEBT AND IT IS NAMED AS ONE. `pnpm api-client:check` is the gate that will fire
 * for it. Regenerating the contract and replacing the type below with the generated one is
 * a two-command change the moment a database is available, and it must happen before this
 * ships — a hand-written response type is a second copy of the contract, free to drift
 * silently, which is the exact thing frontend-nextjs.md forbids.
 *
 * @see docs/40-api/authentication-and-sessions.md § Second factor
 */

/**
 * The password step's 200 body. See the note above: awaiting the generated type.
 *
 * `second_factor` names WHICH factor rather than saying "yes", so the client draws the
 * right second step. There is one value it can take — `totp` — and there must never be an
 * `sms` one: this product removed its phone one-time-code channel deliberately, and a
 * second factor that can arrive by SMS is one SIM swap away from being no second factor.
 */
type ChallengeRequired = {
  data: {
    second_factor: string
    expires_in: number
  }
}

export type SignInOutcome =
  | { readonly kind: 'code_required' }
  | { readonly kind: 'signed_in'; readonly operator: Operator }
  | { readonly kind: 'problem'; readonly problem: SignInProblem; readonly message: string }

/**
 * Step one. Proves the password; never returns a session.
 *
 * The address is lowercased here as well as on the API, for the ordinary reason: addresses
 * are not case-sensitive in practice, and "Sarah@" failing where "sarah@" works is a
 * support call rather than a security control. It is not a validation — nothing here
 * decides whether an address is real, and a client-side rule that guessed would refuse
 * correct ones.
 */
export async function signInWithPassword(email: string, password: string): Promise<SignInOutcome> {
  const result = await postAndKeepSession<ChallengeRequired>('/v1/platform/auth/sign-in', {
    email: email.trim().toLowerCase(),
    password,
  })

  if (result.ok) {
    return { kind: 'code_required' }
  }

  return refusal('password', result)
}

/**
 * Step two. The request that actually opens the session.
 *
 * ONE OF TWO CREDENTIALS, NEVER BOTH — the API refuses a request carrying a code and a
 * recovery code together, because a precedence rule on a credential check is a way of
 * choosing which of two comparisons an attacker gets to skip. So the field that is empty is
 * omitted rather than sent as an empty string, which `exactOptionalPropertyTypes` makes a
 * deliberate act rather than an accident of spreading a form.
 */
export async function completeChallenge(
  credential: string,
  kind: 'code' | 'recovery_code',
): Promise<SignInOutcome> {
  const body = kind === 'code'
    ? { code: credential.trim() }
    : { recovery_code: credential.trim() }

  const result = await postAndKeepSession<{ data: Operator }>('/v1/platform/auth/challenge', body)

  if (result.ok) {
    return { kind: 'signed_in', operator: result.value.data }
  }

  return refusal('code', result)
}

/**
 * Leave.
 *
 * Reachable by a session that has not completed a second factor — it is the one route the
 * API's `RequireSecondFactor` permits — because somebody who cannot proceed must still be
 * able to close what they opened. On a shared machine the alternative is walking away from
 * a half-open session.
 *
 * Failures are swallowed on purpose. There is no useful thing to tell an operator who
 * asked to sign out and whose request did not reach the API: the local cookie is cleared
 * either way by the redirect that follows, and a "sign-out failed" screen with a Try again
 * button is worse than the truth, which is that the session may still be live server-side
 * and will idle out in fifteen minutes.
 */
export async function signOut(): Promise<void> {
  await postAndKeepSession<null>('/v1/platform/auth/sign-out', {})
}

/**
 * Turn a refusal into something a screen can draw.
 *
 * The API's OWN SENTENCE travels, always. It is the only place that knows why — that the
 * account has no authenticator enrolled, that the five minutes ran out, that the limiter
 * has engaged — and paraphrasing it here would produce a screen that is confidently wrong
 * during the one incident somebody needed it.
 */
function refusal(
  step: 'password' | 'code',
  result: Extract<SessionCall<unknown>, { ok: false }>,
): SignInOutcome {
  return {
    kind: 'problem',
    problem: problemFor(step, result.code, result.status),
    message: result.message,
  }
}
